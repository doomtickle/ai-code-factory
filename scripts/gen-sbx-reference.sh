#!/usr/bin/env bash
set -euo pipefail

# Usage: scripts/gen-sbx-reference.sh [OUTFILE]      (run on the host, where sbx is installed)
#
# Saves the installed sbx CLI's own help text to docs/reference/sbx-cli.md so
# agents can check a flag before using it: sbx is not installed in role
# sandboxes. Runs only `sbx version` and `sbx [SUBCOMMAND...] --help`, with a
# fixed argv from the list below (the subcommands the factory's scripts and
# docs use), through no shell and no network. The file is stamped with the sbx
# version and the date; `factory doctor` warns when it drifts from SBX_VERSION.
# Review the file before committing it: it is sbx's output, copied verbatim.
# Exits 1 (after writing the file) if any help command failed.

# shellcheck source=lib/common.sh
. "$(dirname "$0")/lib/common.sh"
require_bin sbx

ROOT="$(cd "$(dirname "$0")/.." && pwd -P)"
out="${1:-$ROOT/docs/reference/sbx-cli.md}"

# One entry per help text; each word is one argv element (no quoting, no shell).
COMMANDS=(
  ""
  "run" "create" "exec" "ls" "rm" "stop" "ports" "login"
  "secret" "secret set" "secret ls" "secret rm"
  "mcp" "mcp add" "mcp ls" "mcp rm"
  "policy" "policy init" "policy check" "policy check network" "policy allow" "policy allow network" "policy ls" "policy reset"
  "template" "template ls" "template load"
  "settings" "settings get" "settings set"
  "daemon" "daemon restart"
  "kit" "kit validate"
)

version="$(sbx_installed_version)"
[ -n "$version" ] || die "could not read the sbx version from 'sbx version'"
[ "$version" = "$SBX_VERSION" ] \
  || echo "warning: installed sbx is $version but the factory pins $SBX_VERSION; the file will say $version and 'factory doctor' will warn" >&2

mkdir -p "$(dirname "$out")"
tmp="$(mktemp "$out.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

# run_section HEADING ARGV... -> a heading and the command's output in a fenced block
failed=0
run_section() {
  local heading="$1" status=0 text
  shift
  text="$(NO_COLOR=1 sbx "$@" 2>&1 </dev/null)" || status=$?
  [ "$status" -eq 0 ] || { failed=$((failed + 1)); echo "failed (exit $status): sbx $*" >&2; }
  {
    printf '\n## `%s`\n\n' "$heading"
    [ "$status" -eq 0 ] || printf '**This command failed (exit %s); the output below is what it printed.**\n\n' "$status"
    printf '````text\n%s\n````\n' "$text"
  } >> "$tmp"
}

cat > "$tmp" <<HEAD
<!-- sbx-reference: version=$version generated=$(date -u +%Y-%m-%d) -->
# sbx CLI reference (sbx $version)

Generated by \`scripts/gen-sbx-reference.sh\` on $(date -u +%Y-%m-%d) from the
installed \`sbx\`'s own help. Do not edit by hand; regenerate after changing
\`SBX_VERSION\` in \`scripts/lib/common.sh\`. It covers only the subcommands the
factory uses. A flag that is not in here is unverified: do not use it without
saying so.
HEAD

run_section "sbx version" version
for c in "${COMMANDS[@]}"; do
  # shellcheck disable=SC2086 # intentional word splitting: one argv element per word
  run_section "sbx${c:+ $c} --help" $c --help
done

chmod 644 "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "Wrote $out (sbx $version)"
[ "$failed" -eq 0 ] || die "$failed help command(s) failed; see the notes in $out"
