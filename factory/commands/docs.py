"""factory docs [--print]: the README, docs/setup-wsl.md and docs/guides/*.md as one
self-contained HTML page, generated by scripts/docs.py at run time.

Printed to stdout with --print or when stdout isn't a terminal; otherwise written to
FACTORY_STATE/docs/index.html and opened in the browser. Needs only python3: no sbx,
Docker or broker/, so it works before 'factory setup'."""

import os
import shutil
import subprocess
import sys

from factory.context import FactoryError

USAGE = "usage: factory docs [--print]"
WINDOWS_COPY = "ai-code-factory-docs.html"


def is_wsl(proc_version="/proc/version"):
    try:
        with open(proc_version, "rb") as f:
            text = f.read().lower()
    except OSError:
        return False
    return b"microsoft" in text or b"wsl" in text


def system_name():
    return os.uname().sysname


def on_wsl(ctx):
    return bool(ctx.environ.get("WSL_DISTRO_NAME")) or is_wsl()


def which(ctx, name):
    return shutil.which(name, path=ctx.environ.get("PATH", os.defpath))


def docs_opener(ctx):
    """The command that opens a file in the browser on this machine: open (macOS),
    wslview (WSL, which maps Linux paths for Windows), else xdg-open. None when it is
    not installed."""
    if system_name() == "Darwin":
        name = "open"
    elif on_wsl(ctx) and which(ctx, "wslview"):
        name = "wslview"
    else:
        name = "xdg-open"
    return name if which(ctx, name) else None


def detached(ctx, argv):
    """Start argv in the background, silenced (stdin, stdout and stderr on /dev/null):
    some openers block, or chatter on stderr. Not waited for."""
    exe = which(ctx, argv[0])
    if not exe:
        return
    null = os.devnull
    actions = [(os.POSIX_SPAWN_OPEN, 0, null, os.O_RDONLY, 0), (os.POSIX_SPAWN_OPEN, 1, null, os.O_WRONLY, 0),
               (os.POSIX_SPAWN_OPEN, 2, null, os.O_WRONLY, 0)]
    try:
        os.posix_spawn(exe, [argv[0]] + argv[1:], dict(ctx.environ), file_actions=actions)
    except OSError:
        pass


def _output(ctx, argv):
    try:
        cp = subprocess.run(argv, env=dict(ctx.environ), stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.DEVNULL)
    except OSError:
        return None
    return cp.stdout.decode("utf-8", "surrogateescape")


def open_docs_on_windows(ctx, page):
    """On WSL, copy `page` into the Windows user's temp folder and open it with the
    Windows default browser. A Windows browser can't always read a page inside the Linux
    filesystem (never one under /root), and wslview isn't reliable everywhere, so the
    page goes where Windows can read it. False (so the caller falls back) when Windows
    interop isn't available."""
    if not all(which(ctx, t) for t in ("cmd.exe", "wslpath", "explorer.exe")):
        return False
    # From a Linux folder cmd.exe warns about the UNC path (on stderr) and still answers.
    out = _output(ctx, ["cmd.exe", "/d", "/c", "echo %TEMP%"])
    if out is None:
        return False
    win_tmp = out.replace("\r", "").rstrip("\n")
    if not (len(win_tmp) >= 3 and win_tmp[0].isascii() and win_tmp[0].isalpha() and win_tmp[1:3] == ":\\"):
        return False
    folder = _output(ctx, ["wslpath", "-u", win_tmp])
    folder = folder.rstrip("\n") if folder else ""
    if not folder or not os.path.isdir(folder):
        return False
    copy = os.path.join(folder, WINDOWS_COPY)
    try:
        shutil.copyfile(page, copy)
    except OSError:
        return False
    win_copy = _output(ctx, ["wslpath", "-w", copy])
    win_copy = win_copy.rstrip("\n") if win_copy else ""
    if not win_copy:
        return False
    # explorer.exe hands the file to the default browser; it exits 1 even on success.
    detached(ctx, ["explorer.exe", win_copy])
    ctx.say("Opening the docs in your Windows browser.")
    ctx.say("If no browser window appears, paste this into your browser's address bar:")
    ctx.say("  " + win_copy)
    return True


def run(ctx, args):
    root, state = ctx.paths.root, ctx.paths.state
    printing = False
    for arg in args:
        if arg != "--print":
            raise FactoryError(USAGE)
        printing = True
    script = [sys.executable, os.path.join(root, "scripts", "docs.py"), "--root", root]
    if printing or not ctx.stdout.isatty():
        return ctx.exec(script)
    if os.geteuid() == 0:
        ctx.warn("running as root: the factory keeps its state in root's home (%s). "
                 "Run factory as your own user, without sudo." % state)
    out = os.path.join(state, "docs", "index.html")
    # Private, like the rest of the state dir.
    old = os.umask(0o077)
    try:
        os.makedirs(os.path.dirname(out), exist_ok=True)
    except OSError as e:
        raise FactoryError("cannot create %s: %s" % (os.path.dirname(out), e.strerror or e))
    finally:
        os.umask(old)
    if ctx.run(script + ["--out", out]) != 0:
        raise FactoryError("could not build the docs")
    if on_wsl(ctx) and open_docs_on_windows(ctx, out):
        return 0
    opener = docs_opener(ctx)
    if opener:
        detached(ctx, [opener, out])
        ctx.say("Opening the docs in your browser: " + out)
    else:
        ctx.say("Docs written to " + out)
        ctx.say("Open that file in a web browser.")
    return 0
